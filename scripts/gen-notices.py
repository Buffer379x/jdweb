#!/usr/bin/env python3
"""Writes web/public/licenses/THIRD_PARTY_NOTICES.txt from the licence files of what ships:
the Go modules the binary is built from (go list -deps ./cmd/jdweb), the Go standard
library, and the production npm dependencies that end up in the web bundle.

Run it from the repository root after `pnpm --dir web install` whenever go.mod or
web/package.json change:  python3 scripts/gen-notices.py
"""
import json, os, pathlib, subprocess, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "web" / "public" / "licenses" / "THIRD_PARTY_NOTICES.txt"
NAMES = ("LICENSE", "LICENCE", "COPYING", "NOTICE", "PATENTS")


def sh(*args, cwd=ROOT):
    return subprocess.run(args, cwd=cwd, check=True, capture_output=True, text=True).stdout


def license_files(d: pathlib.Path):
    return sorted(p for p in d.iterdir() if p.is_file() and p.name.upper().startswith(NAMES))


def section(title, files):
    out = ["=" * 78, title, "=" * 78, ""]
    for f in files:
        if len(files) > 1:
            out += ["--- " + f.name + " ---", ""]
        out += [f.read_text(encoding="utf-8", errors="replace").strip("\n"), ""]
    return "\n".join(out)


def go_modules():
    out = sh("go", "list", "-deps", "-f", "{{if not .Standard}}{{with .Module}}{{.Path}}\t{{.Version}}\t{{.Dir}}{{end}}{{end}}", "./cmd/jdweb")
    seen = {}
    for line in out.splitlines():
        if not line.strip():
            continue
        path, ver, d = line.split("\t")
        if path == "github.com/Buffer379x/jdweb":
            continue
        seen[path] = (ver, pathlib.Path(d))
    return sorted(seen.items())


def go_std():
    goroot = pathlib.Path(sh("go", "env", "GOROOT").strip())
    for d in (goroot, goroot.parent):
        files = license_files(d)
        if any(f.name == "LICENSE" for f in files):
            return files
    sys.exit("cannot find the LICENSE of the Go distribution")


def npm_prod():
    # pnpm lists the production tree; the licence files come from its store directories.
    tree = json.loads(sh("pnpm", "--dir", "web", "ls", "--prod", "--depth", "Infinity", "--json"))
    pkgs = {}

    def walk(deps):
        for name, info in (deps or {}).items():
            pkgs[(name, info["version"])] = pathlib.Path(info["path"])
            walk(info.get("dependencies"))

    for t in tree:
        walk(t.get("dependencies"))
    return sorted(pkgs.items())


def main():
    parts = [
        "Third-party notices for JDWeb\n\n"
        "JDWeb itself is under the MIT licence (LICENSE). The image and the web app contain the\n"
        "software below, each under the licence text that follows its name. The fonts (Barlow,\n"
        "Barlow Condensed, IBM Plex Mono) are under the SIL Open Font License; their texts are in\n"
        "the files OFL-*.txt next to this one.\n"
        "Generated by scripts/gen-notices.py.\n"
    ]
    parts.append(section("Go standard library and runtime (" + sh("go", "env", "GOVERSION").strip() + ")", go_std()))
    for path, (ver, d) in go_modules():
        parts.append(section(f"{path} {ver}", license_files(d)))
    for (name, ver), d in npm_prod():
        parts.append(section(f"{name} {ver} (npm)", license_files(d)))
    OUT.write_text("\n".join(parts) + "\n", encoding="utf-8")
    print("wrote", OUT.relative_to(ROOT))


main()
